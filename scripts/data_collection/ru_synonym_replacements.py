def apply_synonym_replacement(text: str, rate: float = 0.15, seed: int | None = None) -> str:
    """Заменить до ~rate доли вхождений выбранных слов (целые слова, кириллица)."""
    if seed is not None:
        random.seed(seed)
    words = list(_SYNONYMS.keys())
    out = text
    for w in words:
        pattern = re.compile(rf"(?<![а-яёА-ЯЁ]){re.escape(w)}(?![а-яёА-ЯЁ])", re.IGNORECASE)

        def repl(m: re.Match) -> str:
            if random.random() > rate:
                return m.group(0)
            syn = random.choice(_SYNONYMS[w])
            g = m.group(0)
            if g and g[0].isupper():
                return syn.capitalize()
            return syn

        out = pattern.sub(repl, out)
    return out
