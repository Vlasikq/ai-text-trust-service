DOMAIN_CONFIG = {
    "news": {
        "topics": NEWS_TOPICS,
        "templates": NEWS_PROMPT_TEMPLATES,
        "char_range": (1000, 3500),
    },
    "wiki": {
        "topics": WIKI_ENTITIES,
        "templates": WIKI_PROMPT_TEMPLATES,
        "char_range": (2000, 5500),
    },
    "essay": {
        "topics": ESSAY_TOPICS,
        "templates": ESSAY_PROMPT_TEMPLATES,
        "char_range": (1500, 4000),
    },
}

TEMPERATURES = [0.7, 0.8, 0.9, 1.0]


def load_done_ids(path: Path) -> set[str]:
    if not path.exists():
        return set()
    done = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        try:
            pid = json.loads(line).get("meta", {}).get("prompt_id")
            if pid:
                done.add(pid)
        except Exception:
            continue
    return done


def build_prompt_table(domain: str, count: int) -> list[dict]:
    cfg = DOMAIN_CONFIG[domain]
    topics = cfg["topics"]
    templates = cfg["templates"]
    lo, hi = cfg["char_range"]

    rng = random.Random(SEED)
    prompts = []
    for i in range(count):
        topic = topics[i % len(topics)]
        target_chars = rng.randint(lo, hi)
        temperature = rng.choice(TEMPERATURES)
        template = rng.choice(templates)

        system_msg = template["system"]
        user_msg = template["user"].format(
            topic=topic,
            entity=topic,
            target_chars=target_chars,
            target_chars_hi=target_chars + 500,
        )

        prompt_id = f"{domain}_{i:05d}"
        prompts.append({
            "prompt_id": prompt_id,
            "domain": domain,
            "topic": topic,
            "target_chars": target_chars,
            "temperature": temperature,
            "system": system_msg,
            "user": user_msg,
        })
    return prompts


def generate_dataset(
    llm: LLMBackend,
    domain: str,
    count: int,
    sleep_s: float = 0.3,
) -> Path:
    GEN_DIR.mkdir(parents=True, exist_ok=True)

    model_safe = llm.model_name.replace("/", "_").replace(":", "_")
    out_path = GEN_DIR / f"{model_safe}_{domain}.jsonl"

    done_ids = load_done_ids(out_path)
    prompts = build_prompt_table(domain, count)
    remaining = [p for p in prompts if p["prompt_id"] not in done_ids]
    log.info(f"{model_safe}/{domain}: done={len(done_ids)}, remaining={len(remaining)}")

    if not remaining:
        return out_path

    generated = 0
    errors = 0

    with out_path.open("a", encoding="utf-8") as f:
        for i, p in enumerate(remaining):
            text = llm.generate(p["system"], p["user"], p["temperature"])

            if text is None or len(text) < 200:
                errors += 1
                log.warning(f"[{i+1}/{len(remaining)}] SKIP {p['prompt_id']}: empty or too short")
                continue

            row = {
                "text": text,
                "label": "ai",
                "domain": p["domain"],
                "source_name": llm.model_name,
                "doc_id": f"ai_{uuid.uuid4()}",
                "created_at": str(date.today()),
                "meta": {
                    "prompt_id": p["prompt_id"],
                    "topic": p["topic"],
                    "target_chars": p["target_chars"],
                    "temperature": p["temperature"],
                    "actual_chars": len(text),
                },
            }

            f.write(json.dumps(row, ensure_ascii=False) + "\n")
            f.flush()
            generated += 1

            if (i + 1) % 50 == 0 or (i + 1) == len(remaining):
                log.info(
                    f"[{i+1}/{len(remaining)}] Generated: {generated}, Errors: {errors}, "
                    f"Last len: {len(text)}"
                )

            time.sleep(sleep_s)

    log.info(f"Done: {generated} generated, {errors} errors -> {out_path}")
    return out_path


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Generate AI text dataset via LLM APIs")
    p.add_argument(
        "--backend",
        choices=["openai", "gigachat", "yandex", "gemini"],
        default="openai",
        help="LLM backend (default: openai)",
    )
    p.add_argument("--model", default=None, help="Model name (auto-detected if not set)")
    p.add_argument("--domain", choices=["news", "wiki", "essay", "all"], default="all")
    p.add_argument("--count", type=int, default=1000, help="Texts per domain (default: 1000)")
    p.add_argument("--base-url", default=None, help="Custom API base URL (OpenAI backend)")
    p.add_argument("--api-key", default=None, help="API key (or use env vars)")
    p.add_argument("--sleep", type=float, default=0.3, help="Delay between requests (s)")
    p.add_argument(
        "--preset",
        choices=["full", "quick"],
        default=None,
        help="full: 3 domains x 1000; quick: 3 domains x 50",
    )
    return p.parse_args()


def main() -> int:
    args = parse_args()

    if args.preset == "full":
        domains = ["news", "wiki", "essay"]
        count = 1000
    elif args.preset == "quick":
        domains = ["news", "wiki", "essay"]
        count = 50
    elif args.domain == "all":
        domains = ["news", "wiki", "essay"]
        count = args.count
    else:
        domains = [args.domain]
        count = args.count

    llm = create_backend(args.backend, args.model, args.base_url, args.api_key)

    for domain in domains:
        log.info(f"=== {llm.model_name} / {domain} / {count} texts ===")
        generate_dataset(llm, domain, count, sleep_s=args.sleep)

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
