# Граница слова — кириллица/латиница. Re-используем для всех проверок.
_WORD_CHAR = re.compile(r"[а-яёa-z]", re.IGNORECASE)


def find_matched_phrases(text: str, terms: tuple[str, ...] = FORMAL_CONNECTORS) -> list[str]:
    """Список уникальных терминов из словаря, найденных в тексте.

    Порядок результата соответствует первому вхождению в тексте, регистр
    сохраняется как в словаре (для UI), повторы исключаются.
    """
    if not text:
        return []

    lower = text.lower()
    seen: set[str] = set()
    matches: list[tuple[int, str]] = []
    for term in terms:
        t = term.lower()
        idx = lower.find(t)
        while idx >= 0:
            prev_ch = lower[idx - 1] if idx > 0 else " "
            end = idx + len(t)
            next_ch = lower[end] if end < len(lower) else " "
            if not _WORD_CHAR.match(prev_ch) and not _WORD_CHAR.match(next_ch):
                if term not in seen:
                    seen.add(term)
                    matches.append((idx, term))
                break
            idx = lower.find(t, idx + 1)

    matches.sort(key=lambda x: x[0])
    return [term for _, term in matches]
